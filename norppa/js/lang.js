  const bare = (s) => (/^[a-z]+\|/.test(s) ? s.slice(s.indexOf('|') + 1) : s);

  /* The text for this language, with {0}, {1} filled in from the other arguments. */
  PN.L = function (s) {
    let out = fi() && FI[s] != null ? FI[s] : bare(s);
    if (arguments.length > 1) { const a = arguments; out = out.replace(/\{(\d)\}/g, (m, i) => a[+i + 1]); }
    return out;
  };
